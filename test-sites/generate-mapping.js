#!/usr/bin/env node

/**
 * Generate html-scanner-mapping.js from WCAG-TEST metadata blocks.
 *
 * Reads all HTML files in test-sites/, parses their WCAG-TEST comment blocks,
 * and writes the mapping file. The mapping becomes a build artifact, not source of truth.
 */

const fs = require('fs');
const path = require('path');
const { parseDirectory } = require('./wcag-metadata-parser');

const TEST_DIR = __dirname;
const OUTPUT_FILE = path.join(TEST_DIR, 'html-scanner-mapping.js');

/**
 * All known scanners in the system.
 */
const AVAILABLE_SCANNERS = [
  'color-contrast',
  'use-of-color',
  'images-of-text',
  'advanced-contrast',
  'nontext-contrast',
  'text-resize',
  'screen-reader',
  'media-accessibility',
  'language-detection',
  'predictable-navigation',
  'error-handling',
  'html-validation',
  'page-structure',
  'label-in-name',
  'status-messages',
  'advanced-aria',
  'seizure-prevention',
  'timing-controls',
  'keyboard-navigation',
  'focus-management',
  'input-modalities',
  'responsive-design',
  'mobile-specific',
  'dynamic-spa',
  'accessibility-statement',
  'contact-mechanism',
  'compliance-monitoring',
  'eaa-procedure',
];

/**
 * Default excluded scanners for a given test type.
 * Good files: exclude all scanners listed in `scanners` (they should NOT trigger).
 * Bad files: exclude common unrelated scanners.
 */
function deriveExcludedScanners(meta) {
  if (meta.testType === 'good') {
    return meta.scanners || [];
  }
  // For bad files, exclude scanners not in the expected set
  // Default: exclude the most common unrelated ones
  const expected = new Set(meta.scanners || []);
  const commonExclusions = ['color-contrast', 'use-of-color', 'images-of-text', 'keyboard-navigation'];
  return commonExclusions.filter(s => !expected.has(s));
}

function generate() {
  const { parsed, unparsed } = parseDirectory(TEST_DIR);

  if (unparsed.length > 0) {
    console.warn(`Warning: ${unparsed.length} HTML files without WCAG-TEST metadata:`);
    unparsed.forEach(f => console.warn(`  - ${f}`));
  }

  // Build mapping object
  const mapping = {};
  for (const meta of parsed) {
    mapping[meta.file] = {
      expectedScanners: meta.testType === 'bad' ? (meta.scanners || []) : [],
      excludedScanners: deriveExcludedScanners(meta),
      testType: meta.testType,
      wcagCriteria: meta.criterion,
      description: meta.description || meta.title,
    };
  }

  // Generate JS source
  const mappingJson = JSON.stringify(mapping, null, 2);

  const source = `#!/usr/bin/env node

/**
 * HTML File to Scanner Mapping Configuration
 *
 * AUTO-GENERATED by generate-mapping.js — do not edit manually.
 * Source of truth: WCAG-TEST comment blocks in HTML test files.
 *
 * Generated: ${new Date().toISOString()}
 * Files parsed: ${parsed.length}
 */

const HTML_SCANNER_MAPPING = ${mappingJson};

const AVAILABLE_SCANNERS = ${JSON.stringify(AVAILABLE_SCANNERS, null, 2)};

function getTestFilesByType(type) {
  return Object.keys(HTML_SCANNER_MAPPING).filter(
    fileName => HTML_SCANNER_MAPPING[fileName].testType === type
  );
}

function getExpectedScannersForFile(fileName) {
  return HTML_SCANNER_MAPPING[fileName]?.expectedScanners || [];
}

function getExcludedScannersForFile(fileName) {
  return HTML_SCANNER_MAPPING[fileName]?.excludedScanners || [];
}

function getFilesForScanner(scannerName) {
  return Object.keys(HTML_SCANNER_MAPPING).filter(fileName =>
    HTML_SCANNER_MAPPING[fileName].expectedScanners.includes(scannerName)
  );
}

function getFilesExcludingScanner(scannerName) {
  return Object.keys(HTML_SCANNER_MAPPING).filter(fileName =>
    HTML_SCANNER_MAPPING[fileName].excludedScanners.includes(scannerName)
  );
}

function validateMapping() {
  const issues = [];
  Object.entries(HTML_SCANNER_MAPPING).forEach(([fileName, config]) => {
    const unknownExpected = config.expectedScanners.filter(
      scanner => !AVAILABLE_SCANNERS.includes(scanner)
    );
    const unknownExcluded = config.excludedScanners.filter(
      scanner => !AVAILABLE_SCANNERS.includes(scanner)
    );
    if (unknownExpected.length > 0) {
      issues.push(\`\${fileName}: Unknown expected scanners: \${unknownExpected.join(', ')}\`);
    }
    if (unknownExcluded.length > 0) {
      issues.push(\`\${fileName}: Unknown excluded scanners: \${unknownExcluded.join(', ')}\`);
    }
    const overlap = config.expectedScanners.filter(
      scanner => config.excludedScanners.includes(scanner)
    );
    if (overlap.length > 0) {
      issues.push(\`\${fileName}: Scanner in both expected and excluded: \${overlap.join(', ')}\`);
    }
    if (!config.testType || !['bad', 'good'].includes(config.testType)) {
      issues.push(\`\${fileName}: Invalid or missing testType\`);
    }
    if (!config.wcagCriteria || config.wcagCriteria.length === 0) {
      issues.push(\`\${fileName}: Missing WCAG criteria\`);
    }
  });
  return issues;
}

function generateMappingStatistics() {
  const badFiles = getTestFilesByType('bad');
  const goodFiles = getTestFilesByType('good');
  const scannerUsage = {};
  AVAILABLE_SCANNERS.forEach(scanner => {
    scannerUsage[scanner] = {
      expectedFiles: getFilesForScanner(scanner),
      excludedFiles: getFilesExcludingScanner(scanner),
      totalExpected: getFilesForScanner(scanner).length,
      totalExcluded: getFilesExcludingScanner(scanner).length
    };
  });
  return {
    totalFiles: Object.keys(HTML_SCANNER_MAPPING).length,
    badFiles: badFiles.length,
    goodFiles: goodFiles.length,
    availableScanners: AVAILABLE_SCANNERS.length,
    scannerUsage,
    validationIssues: validateMapping()
  };
}

module.exports = {
  HTML_SCANNER_MAPPING,
  AVAILABLE_SCANNERS,
  getTestFilesByType,
  getExpectedScannersForFile,
  getExcludedScannersForFile,
  getFilesForScanner,
  getFilesExcludingScanner,
  validateMapping,
  generateMappingStatistics
};

if (require.main === module) {
  const stats = generateMappingStatistics();
  console.log('HTML-to-Scanner Mapping Configuration');
  console.log(\`Total test files: \${stats.totalFiles}\`);
  console.log(\`Bad examples: \${stats.badFiles}\`);
  console.log(\`Good examples: \${stats.goodFiles}\`);
  console.log(\`Available scanners: \${stats.availableScanners}\`);
  if (stats.validationIssues.length > 0) {
    console.log('\\nValidation issues:');
    stats.validationIssues.forEach(issue => console.log(\`  \${issue}\`));
  } else {
    console.log('\\nMapping configuration is valid');
  }
}
`;

  fs.writeFileSync(OUTPUT_FILE, source, 'utf-8');
  console.log(`Generated ${OUTPUT_FILE} with ${parsed.length} file entries`);
}

if (require.main === module) {
  generate();
}

module.exports = { generate };
